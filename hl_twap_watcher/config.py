"""Настройки наблюдателя. Значения по умолчанию подобраны под лимиты Hyperliquid."""

__all__ = ["MAX_USERS_PER_WS", "WatcherConfig"]

from dataclasses import dataclass

MAX_USERS_PER_WS = 14
"""Сколько подписок `twapStates` принимает одно WS-соединение.

Биржа отвечает "Cannot track more than 15 total users". Лимит считается на серверную
ноду за балансировщиком, а не на соединение: соединения одного IP, попавшие на одну
ноду, делят 15 слотов. Нод около трех, то есть на IP выходит около 45 кошельков.
14 на соединение оставляет запас под чужие подписки на той же ноде.
"""


@dataclass(frozen=True, slots=True)
class WatcherConfig:
    """Технические параметры наблюдателя.

    Менять стоит, только понимая лимиты биржи: значения по умолчанию взяты из
    рабочего симулятора и укладываются в ограничения Hyperliquid на один IP.
    """

    ws_url: str = "wss://api.hyperliquid.xyz/ws"
    """Адрес WebSocket API."""

    info_url: str = "https://api.hyperliquid.xyz/info"
    """Адрес REST info-эндпоинта."""

    watchers_count: int = 2
    """Число WS-соединений с подписками `twapStates`. У биржи около трех нод по 15
    подписок на IP, поэтому больше трех соединений емкости не добавят. Два оставляют
    ноду свободной для других приложений на том же IP."""

    watch_ttl: float = 5.0
    """Сколько секунд кошелек занимает слот подписки: за это время успевает прийти
    состояние всех его TWAP."""

    queue_wait_seconds: float = 30.0
    """Сколько кандидат может ждать проверки. Из этого считается предел очереди:
    более старые кандидаты выбрасываются — их ордера уже не новые."""

    slice_silence_seconds: float = 90.0
    """Тишина в слайсах, после которой ордер проверяется на завершение. Слайсы
    живого ордера идут примерно раз в 30 секунд — порог взят с тройным запасом."""

    check_cooldown_seconds: float = 60.0
    """Пауза перед повторной проверкой ордера, который оказался живым. Каждая
    следующая неудачная проверка удваивает паузу до `check_max_backoff_seconds`."""

    check_max_backoff_seconds: float = 900.0
    """Предел паузы между проверками: ордер с триггером может молчать часами."""

    finished_grace_seconds: float = 3600.0
    """Сколько ждать сверх запланированного конца ордера, если биржа так и не
    вернула его статус. После этого ордер снимается с наблюдения без события."""

    rest_requests_per_minute: int = 40
    """Сколько контрольных REST-запросов истории ордеров в минуту разрешено.
    Вес запроса — 20 из 1200 в минуту на IP, остальное оставлено пользователю."""

    markets_refresh_seconds: float = 600.0
    """Как часто перечитывать список перпов: подхватывает новые листинги."""

    max_seen_twaps: int = 200_000
    """Размер памяти о найденных ордерах для дедупликации."""

    max_seen_wallets: int = 20_000
    """Размер памяти о проверенных кошельках для дедупликации кандидатов."""

    wallet_dedup_factor: float = 4.0
    """Во сколько раз окно дедупликации кошельков длиннее `watch_ttl`: слайсы одного
    TWAP идут каждые 30 секунд, без окна очередь забьется повторами."""

    @property
    def pool_capacity(self) -> int:
        """Сколько кошельков пул держит в подписке одновременно."""
        return self.watchers_count * MAX_USERS_PER_WS

    @property
    def queue_limit(self) -> int:
        """Предельная глубина очереди кандидатов.

        Слот освобождается каждые `watch_ttl` секунд. Очередь глубже той, что пул
        разберет за `queue_wait_seconds`, состоит из протухших кандидатов.
        """
        return max(1, int(self.pool_capacity * self.queue_wait_seconds / self.watch_ttl))

    @property
    def rest_interval(self) -> float:
        """Минимальная пауза между контрольными REST-запросами, секунды."""
        return 60.0 / max(1, self.rest_requests_per_minute)
