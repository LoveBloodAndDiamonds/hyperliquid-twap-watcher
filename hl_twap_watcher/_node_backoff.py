"""Решение, когда WS-соединению уйти с занятой ноды биржи."""

__all__ = ["NodeBackoff"]

from dataclasses import dataclass

_DELAYS = (5.0, 10.0, 20.0, 40.0, 60.0)
"""Паузы между переподключениями подряд, секунды. Свободная нода находится примерно
с каждой третьей попытки — первые попытки идут быстро. Дальше пауза растет: если
ноды заняты другим приложением на том же IP, спешка не поможет."""

_STABLE_SECONDS = 120.0
"""Сколько соединение должно продержаться без отказов, чтобы серия обнулилась."""


@dataclass
class NodeBackoff:
    """Помнит, занята ли нода соединения, и выдерживает паузы между переподключениями.

    Лимит "15 total users" биржа считает на серверную ноду за балансировщиком, а
    соединение держит не больше 14 кошельков. Поэтому любой отказ по лимиту значит,
    что ноду делит кто-то еще, и соединение стоит пересоздать: балансировщик отправит
    его на случайную ноду.

    Живет дольше соединения: серия переподключений не должна обнуляться реконнектом.
    """

    crowded: bool = False
    """Биржа отказала в подписке по лимиту: нода занята кем-то еще."""

    last_reconnect_at: float = 0.0
    """Когда соединение последний раз уходило с занятой ноды, секунды."""

    streak: int = 0
    """Сколько раз подряд соединение уходило с занятой ноды."""

    def should_reconnect(self, now: float) -> bool:
        """Проверяет, пора ли пересоздать соединение.

        :param now: Текущее время, секунды.
        :return: True, если нода занята и пауза после прошлой попытки выдержана.
        """
        since = now - self.last_reconnect_at

        if not self.crowded:
            # Соединение прижилось на свободной ноде — следующая серия начнется заново.
            if since > _STABLE_SECONDS:
                self.streak = 0
            return False

        # Первый уход с ноды — сразу, следующие подряд — с растущей паузой.
        if self.streak > 0:
            delay = _DELAYS[min(self.streak, len(_DELAYS)) - 1]
            if since < delay:
                return False

        return True

    def reconnecting(self, now: float) -> None:
        """Отмечает, что соединение пересоздается.

        :param now: Текущее время, секунды.
        """
        self.last_reconnect_at = now
        self.streak += 1
        # Новое соединение начинает с чистого листа: занятость покажут новые отказы.
        self.crowded = False
